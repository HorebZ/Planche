use planche_core::auth;
use planche_core::cache::Cache;
use planche_core::sync::SyncCommand;
use tauri::{LogicalSize, Manager, WindowEvent};
use tauri_specta::{ErrorHandlingMode, collect_commands, collect_events};

use crate::commands::Core;

const BINDINGS: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../src/ipc/bindings.ts");

fn builder() -> tauri_specta::Builder<tauri::Wry> {
    tauri_specta::Builder::new()
        .error_handling(ErrorHandlingMode::Throw)
        .commands(collect_commands![
            commands::auth_status,
            commands::auth_set_token,
            commands::auth_sign_out,
            commands::list_projects,
            commands::cached_projects,
            commands::open_project,
            commands::current_project,
            commands::get_project,
            commands::get_board,
            commands::refresh_project,
            commands::dispatch_intent,
            commands::sync_status,
            commands::get_sync_prefs,
            commands::set_sync_prefs,
            commands::perf_mark,
        ])
        .events(collect_events![
            events::BoardChanged,
            events::MutationFailed,
            events::SyncStatusChanged
        ])
}

fn export_bindings(builder: &tauri_specta::Builder<tauri::Wry>) {
    builder
        .export(
            specta_typescript::Typescript::default()
                .header("// Generated by tauri-specta. Do not edit.\n"),
            BINDINGS,
        )
        .expect("bindings export");
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    let builder = builder();
    #[cfg(debug_assertions)]
    export_bindings(&builder);

    tauri::Builder::default()
        .plugin(tauri_plugin_opener::init())
        .invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            builder.mount_events(app);
            let core = Core::new(Cache::open_default()?);
            let reopen = core.current_project().map_err(|e| e.message)?;
            app.manage(core);

            // The onboarding is a small window; the board needs room.
            let window = app.get_webview_window("main").expect("main window");
            let signed_in = auth::load_token().is_ok();
            if signed_in {
                window.set_min_size(Some(LogicalSize::new(1100.0, 700.0)))?;
                window.set_size(LogicalSize::new(1440.0, 900.0))?;
            } else {
                window.set_size(LogicalSize::new(780.0, 540.0))?;
            }
            window.center()?;
            window.show()?;
            window.set_focus()?;

            if let (true, Some(project)) = (signed_in, reopen) {
                let app = app.handle().clone();
                tauri::async_runtime::spawn(async move {
                    let core = app.state::<Core>();
                    if let Err(error) = core.open(&app, &project).await {
                        eprintln!("could not reopen {project}: {}", error.message);
                    }
                });
            }
            Ok(())
        })
        .on_window_event(|window, event| {
            if let WindowEvent::Focused(true) = event {
                let app = window.app_handle().clone();
                tauri::async_runtime::spawn(async move {
                    if let Some(engine) = app.state::<Core>().engine().await {
                        engine.send(SyncCommand::Focus).await;
                    }
                });
            }
        })
        .run(tauri::generate_context!())
        .expect("error while running tauri application");
}

